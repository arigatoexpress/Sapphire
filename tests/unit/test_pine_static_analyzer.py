"""Unit tests for `lib.pine.static_analyzer`.

Pins current analyzer behavior so future edits to either the analyzer or
`lib.trading.pine_templates` don't silently drift the Pine ↔ webhook
contract. Tests run without the `tv` CLI — they exercise the offline
pattern-matching path only.
"""

from __future__ import annotations

from lib.pine import analyze_pine_file, analyze_pine_source
from lib.trading.pine_templates import (
    render_sapphire_screener,
    render_sapphire_watch_indicator,
    render_sapphire_watch_strategy,
)

# ---------------------------------------------------------------------------
# Generator output: indicator / strategy / screener should pass clean.
# ---------------------------------------------------------------------------


