# ---------------------------------------------------------------------------
# Row shape contract: every row has a 1-indexed int `line` and a str `msg`.
# ---------------------------------------------------------------------------


def test_error_and_warning_rows_have_line_and_msg_shape():
    # Force at least one error AND one warning in a single source so we can
    # assert the row shape on both.
    src = (
        "// Auto-generated by Sapphire (lib.trading.pine_templates)\n"
        "//@version=5\n"
        'strategy("X", overlay=true)\n'
        'strategy.entry("Long", strategy.long)\n'
        'alert(\'{"symbol": "x", "action": "long", "price": 1.0, '
        '"time": 1, "ts": 1}\', alert.freq_once_per_bar_close)\n'
    )
    result = analyze_pine_source(src)
    assert result["errors"], "expected at least one error in this canned source"
    assert result["warnings"], "expected at least one warning in this canned source"
    for row in (*result["errors"], *result["warnings"]):
        assert set(row.keys()) >= {"line", "msg"}
        assert isinstance(row["line"], int)
        assert row["line"] >= 1
        assert isinstance(row["msg"], str)
        assert row["msg"]


