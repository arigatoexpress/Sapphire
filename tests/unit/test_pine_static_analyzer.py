def test_legacy_ts_field_triggers_contract_drift_error():
    # Sapphire-tagged source so Sapphire-only checks also run; the `"ts":`
    # check is global, but tagging makes the source realistic.
    src = (
        "// Auto-generated by Sapphire (lib.trading.pine_templates)\n"
        "//@version=5\n"
        'indicator("X", overlay=true)\n'
        'alert(\'{"symbol": "BTC", "action": "long", "price": 1.0, '
        '"time": 1, "ts": 1}\', alert.freq_once_per_bar_close)\n'
    )
    result = analyze_pine_source(src)
    ts_errors = [e for e in result["errors"] if '"ts"' in e["msg"]]
    assert len(ts_errors) == 1
    assert ts_errors[0]["line"] == 4
    assert result["ok"] is False


